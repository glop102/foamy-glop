function controlDict(p) {
  const fo = [];
  const first = p.machines[0];
  for (const o of p.machines) {
    if (o === first)
      fo.push(`    // Air going into each machine: the numbers that matter.
    ${o.id}Intake
    {
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            ${o.id}In;
        operation       areaAverage;
        fields          (T);
        writeFields     false;
        writeControl    timeStep;
        writeInterval   10;
        log             false;
    }`);
    else fo.push(`    ${o.id}Intake { $${first.id}Intake; name ${o.id}In; }`);
    fo.push(`    ${o.id}IntakeMax { $${o.id}Intake; operation max; }`);
    fo.push(`    ${o.id}Exhaust { $${o.id}Intake; name ${o.id}Out; }`);
  }
  const flows = [...p.vents.map((o) => [o.id, o.id]), ...p.fans.map((o) => [o.id, o.id]), ...p.ducts.map((d) => [d.id, d.id + "Far"])];
  if (flows.length) fo.push("\n    // Mass flow through each opening, kg/s, positive out of the room.");
  for (const [id, patch] of flows)
    fo.push(`    ${id}Flow
    {
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            ${patch};
        operation       sum;
        fields          (phi);
        writeFields     false;
        writeControl    timeStep;
        writeInterval   10;
        log             false;
        errors          warn;
    }`);
  fo.push(`
    // Heat conducted out through each wall, W.
    wallHeat
    {
        type            wallHeatFlux;
        libs            (fieldFunctionObjects);
        patches         (${p.walls.map((w) => w.patch).join(" ")});
        writeFields     false;
        writeControl    timeStep;
        writeInterval   100;
        log             false;
    }

    air
    {
        type            volFieldValue;
        libs            (fieldFunctionObjects);
        operation       volAverage;
        fields          (T);
        writeFields     false;
        writeControl    timeStep;
        writeInterval   10;
        log             false;
    }
    airMax { $air; operation max; }`);

  // Plot planes through the hottest machine (or the middle of the room),
  // nudged off cell faces; in metres since the solver runs after scaling.
  const hot = [...p.machines, ...p.heaters].sort((a, b) => b.power - a.power)[0];
  const centre = hot ? [0, 1, 2].map((i) => (hot.min[i] + hot.max[i]) / 2) : [p.W / 2, p.D / 2, p.H / 2];
  const frontY = hot && hot.min[1] > 6 ? hot.min[1] / 2 : centre[1];
  const cuts = {
    side: [[centre[0] + 0.3, 0, 0], [1, 0, 0]],
    front: [[0, frontY + 0.3, 0], [0, 1, 0]],
    top: [[0, 0, centre[2] + 0.1], [0, 0, 1]],
  };
  const d = p.ducts[0];
  if (d && Math.abs(d.g.centre[0] - d.g.farCentre[0]) < 1e-6) cuts.duct = [[d.g.centre[0] + 0.3, 0, 0], [1, 0, 0]];
  fo.push(`
    cuts
    {
        type            surfaces;
        libs            (sampling);
        writeControl    writeTime;
        surfaceFormat   raw;
        fields          (T U);
        interpolationScheme cell;

        surfaces
        {
${Object.entries(cuts)
  .map(([k, [pt, nrm]]) => `            ${k}\n            {\n                type        cuttingPlane;\n                planeType   pointAndNormal;\n                pointAndNormalDict { point ${vec(pt.map((x) => x * INCH))}; normal ${vec(nrm)}; }\n                interpolate false;\n            }`)
  .join("\n")}
        }
    }`);

  const iterations = Math.max(1, Math.round(p.s.solver.iterations));
  let writeEvery = Math.min(500, iterations);
  while (iterations % writeEvery) writeEvery--;
  return (
    header("dictionary", "controlDict") +
    `application     buoyantSimpleFoam;

startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         ${iterations};   // steady state: "time" is the iteration count
deltaT          1;

// Divides endTime, so the last iteration is a write (and the cuts get made).
writeControl    timeStep;
writeInterval   ${writeEvery};
purgeWrite      1;

writeFormat     binary;
writePrecision  8;
writeCompression off;
timeFormat      general;
timePrecision   6;
runTimeModifiable false;

functions
{
${fo.join("\n")}
}
` + FOOTER
  );
}

