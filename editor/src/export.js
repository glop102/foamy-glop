// ---- Scripts --------------------------------------------------------------------

function allrun(p) {
  // Patches with a fixed airflow must catch some faces, or the flow divides
  // by zero area. Openings with none just do nothing, which is worth saying.
  const mustHave = [...p.machines.flatMap((o) => [o.id + "In", o.id + "Out"]), ...p.fans.map((o) => o.id)];
  const shouldHave = p.openings.map((o) => o.id);
  return `#!/bin/sh
# Mesh and solve this case in place, then summarise it into report.txt if
# foamy-report is on PATH (it is inside the foamy-glop 'nix develop' shell).
#
#   ./Allrun                 # picks a process count from the mesh size
#   NPROCS=16 ./Allrun
cd "\${0%/*}" || exit 1
. "\${WM_PROJECT_DIR:?run this inside 'nix develop'}"/bin/tools/RunFunctions

./Allclean

runApplication blockMesh
runApplication topoSet
runApplication subsetMesh air -patch surfaces -overwrite
runApplication -s patches topoSet -dict system/topoSetDict.patches
runApplication createPatch -overwrite
runApplication transformPoints -scale ${INCH}
runApplication checkMesh

# Faces in a patch, from the mesh's boundary file.
faces() {
    awk -v p="$1" '$1 == p { found = 1 } found && $1 == "nFaces" { print $2 + 0; exit }' \\
        constant/polyMesh/boundary
}
missing=""
for patch in ${mustHave.join(" ")}
do
    [ "$(faces "$patch")" -gt 0 ] 2>/dev/null || missing="$missing $patch"
done
for patch in ${shouldHave.join(" ")}
do
    [ "$(faces "$patch")" -gt 0 ] 2>/dev/null || echo "Warning: $patch caught no faces, so it is closed." >&2
done
if [ -n "$missing" ]
then
    echo "These fans or machine faces caught no faces, so their airflow has nowhere to go:$missing" >&2
    echo "Move them onto a surface (or out from behind another solid) and export again." >&2
    exit 1
fi

cp -r 0.orig 0

# About one process per 30k cells, up to half the CPUs: splitting a small
# mesh further costs more in talking than it saves in solving.
if [ -z "\${NPROCS:-}" ]
then
    cells=$(awk '$1 == "cells:" { print $2; exit }' log.checkMesh)
    NPROCS=$(( \${cells:-0} / 30000 ))
    max=$(( $(nproc) / 2 ))
    [ "$NPROCS" -le "$max" ] || NPROCS=$max
fi
[ "$NPROCS" -ge 1 ] 2>/dev/null || NPROCS=1

if [ "$NPROCS" -gt 1 ]
then
    foamDictionary -entry numberOfSubdomains -set "$NPROCS" \\
        system/decomposeParDict > /dev/null 2>&1
    runApplication decomposePar
    runParallel "$(getApplication)"
    runApplication reconstructPar -latestTime
    rm -rf processor*
else
    runApplication "$(getApplication)"
fi

grep -q "^End" "log.$(getApplication)" || {
    echo "Solver did not finish, see log.$(getApplication)" >&2
    exit 1
}

if command -v foamy-report > /dev/null
then
    foamy-report . | tee report.txt
fi
`;
}

const ALLCLEAN = `#!/bin/sh
cd "\${0%/*}" || exit 1
. "\${WM_PROJECT_DIR:?run this inside 'nix develop'}"/bin/tools/CleanFunctions

cleanCase0
rm -f *.png report.txt
`;

function readme(p) {
  const s = p.s;
  return [
    `# ${s.name}`,
    "",
    s.notes || "",
    "",
    "Generated by the foamy-glop editor. `scenario.json` is the source: load it",
    "back into the editor to change anything, then export again.",
    "",
    "```sh",
    "nix develop /path/to/foamy-glop   # OpenFOAM and foamy-report",
    "./Allrun",
    "```",
    "",
    `${s.items.length} items, ${s.solver.iterations} iterations.`,
    "",
  ].join("\n");
}

// ---- Entry point ----------------------------------------------------------------

export function exportCase(scenario) {
  const problems = validate(scenario);
  const errors = problems.filter((x) => x.level === "error");
  if (errors.length) {
    const e = new Error("The scenario has errors:\n" + errors.map((x) => "  " + x.msg).join("\n"));
    e.problems = problems;
    throw e;
  }
  const p = plan(snapped(scenario));
  const { dict: patchesDict, created } = topoSetPatches(p);
  const files = {
    "scenario.json": JSON.stringify(scenario, null, 2) + "\n",
    "README.md": readme(p),
    Allrun: { content: allrun(p), mode: 0o755 },
    Allclean: { content: ALLCLEAN, mode: 0o755 },
    "system/blockMeshDict": blockMeshDict(p),
    "system/topoSetDict": topoSetDict(p),
    "system/topoSetDict.patches": patchesDict,
    "system/createPatchDict": createPatchDict(created),
    "system/controlDict": controlDict(p),
    "system/fvOptions": fvOptions(p),
    "system/fvSchemes": header("dictionary", "fvSchemes") + FV_SCHEMES + FOOTER,
    "system/fvSolution": header("dictionary", "fvSolution") + FV_SOLUTION + FOOTER,
    "system/decomposeParDict": header("dictionary", "decomposeParDict") + "// Allrun sets this from $NPROCS.\nnumberOfSubdomains  2;\n\nmethod              scotch;\n" + FOOTER,
    "constant/g": header("uniformDimensionedVectorField", "g") + "dimensions      [0 1 -2 0 0 0 0];\nvalue           (0 0 -9.81);\n" + FOOTER,
    "constant/hRef": header("uniformDimensionedScalarField", "hRef") + `// Height air is expected to leave by (${num(p.outflowHeight)} in).\ndimensions      [0 1 0 0 0 0 0];\nvalue           ${num(p.outflowHeight * INCH)};\n` + FOOTER,
    "constant/thermophysicalProperties": thermo(p),
    "constant/turbulenceProperties": header("dictionary", "turbulenceProperties") + "simulationType  RAS;\n\nRAS\n{\n    model           kEpsilon;\n    turbulence      on;\n    printCoeffs     off;\n}\n" + FOOTER,
    "0.orig/T": fieldT(p),
    "0.orig/U": fieldU(p),
    "0.orig/p_rgh": fieldPrgh(p),
    "0.orig/p": fieldP(),
    "0.orig/k": turbulence(p, "k", "[0 2 -2 0 0 0 0]", "1e-3", "kqRWallFunction", "5e-3"),
    "0.orig/epsilon": turbulence(p, "epsilon", "[0 2 -3 0 0 0 0]", "1e-4", "epsilonWallFunction", "3e-3"),
    "0.orig/nut": wallOnly(p, "nut", "[0 2 -1 0 0 0 0]", "type            nutkWallFunction;\nvalue           $internalField;"),
    "0.orig/alphat": wallOnly(p, "alphat", "[1 -1 -1 0 0 0 0]", "type            compressible::alphatJayatillekeWallFunction;\nPrt             0.85;\nvalue           $internalField;"),
  };
  const out = {};
  for (const [path, f] of Object.entries(files)) out[path] = typeof f === "string" ? { content: f, mode: 0o644 } : f;
  return { files: out, problems };
}
